/**
 * The Kitchen Codex — Advanced Nutrition Phase 9B-2B.
 * PROCESS-SCOPED SEMANTIC-ORIGIN RECEIPT AUTHORITY OWNER (F-05).
 *
 * WHY THIS MODULE EXISTS
 *   Phase 9B-2A shipped the semantic-origin proof *primitive*. A primitive is
 *   not enough to issue and verify in the same process: if the operation that
 *   ISSUES a proof and the consumer that VERIFIES it each construct their own
 *   authority, they hold different random keys and every proof fails. Phase
 *   9B-2A's key is process-local by design, so process-local OWNERSHIP is a hard
 *   requirement, not an optimization.
 *
 *   This module is that owner: ONE lazily-created, server-lifetime authority.
 *   Both the semantic operation (issuer) and the future route/consumer
 *   (verifier) obtain the SAME instance, so they share the SAME key.
 *
 * TRUST BOUNDARY (unchanged from 9B-2A)
 *   The key is generated by the 9B-2A authority factory and never leaves this
 *   process: not into a response, a log, an error message, the client bundle, or
 *   persisted data. This module adds no access path to it.
 *
 * PROCESS-LOCAL TRUTH (unchanged, and deliberately NOT solved here)
 *   - a proof survives only for the lifetime of this process;
 *   - a restart invalidates every outstanding proof;
 *   - a second independent instance does not validate this one's proofs.
 *   A future multi-instance deployment needs a shared signing secret or an
 *   equivalent shared verification architecture. That is NOT implemented here and
 *   is NOT pretended to work.
 *
 * NO KEY INJECTION
 *   There is deliberately no way to set the key from the environment or a config
 *   file. A caller-supplied secret is exactly the shortcut the proof primitive
 *   exists to prevent. Tests that need an INDEPENDENT authority simply construct
 *   their own via `createWholeRecipeSemanticOriginAuthority()`.
 */

import {
  createWholeRecipeSemanticOriginAuthority,
  type WholeRecipeSemanticOriginAuthority,
} from './wholeRecipeSemanticOriginReceipt.js';

/** The ONE process-scoped authority, created on first use. */
let processAuthority: WholeRecipeSemanticOriginAuthority | undefined;

/**
 * The process-scoped semantic-origin receipt authority.
 *
 * Idempotent: every call returns the SAME instance, so the issuer and any future
 * verifier share one key for the life of the process.
 *
 * Deliberately NOT resettable in production. There is no exported reset and no
 * environment override, because a key swap would invalidate every outstanding
 * proof. Tests that need two independent authorities create their own.
 */
export function getProcessSemanticOriginAuthority(): WholeRecipeSemanticOriginAuthority {
  if (processAuthority === undefined) {
    processAuthority = createWholeRecipeSemanticOriginAuthority();
  }
  return processAuthority;
}

/**
 * True when this process has already minted its authority.
 *
 * Exists so a test can assert that creating an authority is LAZY (no key is
 * generated at import time) without being able to change or replace it.
 */
export function hasProcessSemanticOriginAuthority(): boolean {
  return processAuthority !== undefined;
}