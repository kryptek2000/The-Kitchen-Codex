// @vitest-environment jsdom
/**
 * SHISO-C1.6-F3 — read-only Signature Recipe Card presentation.
 * No provider, Vault, or generation path is involved.
 */
import { describe, expect, it } from 'vitest';
import { render, screen } from '@testing-library/react';
import { SignatureRecipeCard } from '../../src/components/SignatureRecipeCard';
import type {
  GeneratedRecipeDraft,
  GeneratedRecipeProvenance,
} from '../../src/schema/generatedRecipe';

const PROVENANCE: GeneratedRecipeProvenance = {
  generated: true,
  providerId: 'chatgpt-plan',
  model: 'gpt-6.2-sol',
};

const FULL: GeneratedRecipeDraft = {
  title: 'Southern Cornbread Dressing',
  description: 'Savory holiday dressing.',
  servings: 8,
  prepTime: '20 mins',
  cookTime: '45 mins',
  totalTime: '65 mins',
  ingredients: [
    { amount: 4, unit: 'cup', name: 'crumbled cornbread', preparation: 'day-old', optional: true },
    { name: 'salt' },
  ],
  steps: [
    { text: 'Combine the cornbread and aromatics.', timerMinutes: 10 },
    { text: 'Bake until golden.' },
  ],
  notes: 'Cool before serving.',
};

describe('Signature Recipe Card', () => {
  it('presents the draft as a read-only cookbook page with all safeguards', () => {
    const { container } = render(
      <SignatureRecipeCard draft={FULL} provenance={PROVENANCE} />
    );
    expect(container.querySelector('[data-signature-recipe-card]')).toBeTruthy();
    expect(screen.getByText('Generated Draft')).toBeTruthy();
    expect(screen.getByText('Not saved yet')).toBeTruthy();
    expect(screen.getByText(/AI-generated by chatgpt-plan · gpt-6.2-sol/)).toBeTruthy();
    expect(screen.getByRole('heading', { level: 1, name: 'Southern Cornbread Dressing' })).toBeTruthy();
    expect(screen.getByText('Savory holiday dressing.')).toBeTruthy();
    expect(screen.getByText('For 8 servings')).toBeTruthy();
    expect(screen.getByText('day-old')).toBeTruthy();
    expect(screen.getByText('Optional')).toBeTruthy();
    expect(container.querySelector('.kc-src-timer')?.getAttribute('aria-label')).toBe('Timer 10 minutes');
    expect(container.querySelector('.kc-src-timer')?.textContent).toContain('10 MIN');
    expect(screen.getByText("Cook's note")).toBeTruthy();
    expect(screen.getAllByRole('heading', { level: 2 }).map((h) => h.textContent)).toEqual([
      'Ingredients',
      'Preparation',
    ]);
    expect(screen.getByText('2 steps')).toBeTruthy();
    // No form fields in the default experience.
    expect(container.querySelector('input, textarea, select')).toBeNull();
  });

  it('omits absent fields instead of inventing values', () => {
    const minimal: GeneratedRecipeDraft = {
      title: 'Minimal Toast',
      ingredients: [{ name: 'bread' }],
      steps: [{ text: 'Toast.' }],
    };
    const { container } = render(
      <SignatureRecipeCard draft={minimal} provenance={PROVENANCE} />
    );
    expect(screen.getByRole('heading', { level: 1, name: 'Minimal Toast' })).toBeTruthy();
    expect(container.querySelector('.kc-src-deck')).toBeNull();
    expect(container.querySelector('.kc-src-facts')).toBeNull();
    expect(container.querySelector('.kc-src-note')).toBeNull();
    expect(container.querySelector('.kc-src-opt')).toBeNull();
    expect(container.querySelector('.kc-src-timer')).toBeNull();
    expect(screen.getByText('1 step')).toBeTruthy();
  });

  it('shows friendly fractions in the card without mutating the numeric draft', () => {
    const fractional: GeneratedRecipeDraft = {
      title: 'Fraction Test',
      ingredients: [
        { amount: 1.25, unit: 'cup', name: 'flour' },
        { amount: 0.75, name: 'milk' },
        { amount: 0.25, name: 'salt' },
        { amount: 0.5, unit: 'tsp', name: 'sage' },
        { amount: 2.75, unit: 'tbsp', name: 'butter' },
        { amount: 1.1, name: 'pepper' },
      ],
      steps: [{ text: 'Mix.' }],
    };
    render(<SignatureRecipeCard draft={fractional} provenance={PROVENANCE} />);
    expect(screen.getByText('1¼')).toBeTruthy();
    expect(screen.getByText('¾')).toBeTruthy();
    expect(screen.getByText('¼')).toBeTruthy();
    expect(screen.getByText('½')).toBeTruthy();
    expect(screen.getByText('2¾')).toBeTruthy();
    expect(screen.getByText('1.1')).toBeTruthy();
    expect(fractional.ingredients.map((i) => i.amount)).toEqual([1.25, 0.75, 0.25, 0.5, 2.75, 1.1]);
  });

  it('renders photography only when a legitimate image is actually supplied', () => {
    const { container, rerender } = render(
      <SignatureRecipeCard draft={FULL} provenance={PROVENANCE} />
    );
    expect(container.querySelector('figure.kc-src-hero')).toBeNull();

    rerender(
      <SignatureRecipeCard
        draft={FULL}
        provenance={PROVENANCE}
        image={{ url: '/images/owner-approved.jpg', alt: 'The finished dressing', credit: 'Owner photograph' }}
      />
    );
    const hero = container.querySelector('figure.kc-src-hero');
    expect(hero).toBeTruthy();
    expect(screen.getByAltText('The finished dressing')).toBeTruthy();
    expect(screen.getByText('Owner photograph')).toBeTruthy();
  });
});
