import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import http from "node:http";
import type { AddressInfo } from "node:net";
import { ImagePreviewStore } from "../../server/imagePreviewStore.js";
import { bootstrapImageSession } from "../helpers/imageSessionTestClient.js";

/**
 * P2 — OpenAI Image through TKC's EXISTING secure image workflow.
 *
 * Boots the real Express app with a mocked OpenAI Images transport and proves:
 *   - OpenAI Image is OPT-IN (no header -> Gemini default, zero OpenAI calls);
 *   - the quote issues a single-use confirmation token (variable pricing) with
 *     ZERO provider calls;
 *   - generate requires that token and calls OpenAI exactly once;
 *   - the generated bytes flow through the shared validation + transient preview
 *     store (no vault write, no automatic save);
 *   - organization-verification failures map to a distinct, bounded 403.
 */

const KEY = "sk-openai-P2-ROUTE-KEY";
const MODEL = "gpt-image-2.6-flare";
const IMAGE_HEADER = "x-kitchen-ai-image-selection";
const VALID_PNG_B64 =
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==";

const ENV_KEYS = [
  "GEMINI_API_KEY",
  "OPENROUTER_API_KEY",
  "OPENAI_API_KEY",
  "KITCHEN_CODEX_IMAGE_PROVIDER",
  "KITCHEN_CODEX_IMAGE_MODEL",
  "AI_ENDPOINT_TOKEN",
  "KITCHEN_CODEX_SESSION_BYOK",
  "KITCHEN_CODEX_DISABLE_SESSION_BYOK",
  "K_SERVICE",
  "K_REVISION",
  "K_CONFIGURATION",
  "HOST",
] as const;

const realFetch = globalThis.fetch.bind(globalThis);

function selectionHeader(overrides: Record<string, unknown> = {}): Record<string, string> {
  return {
    "Content-Type": "application/json",
    [IMAGE_HEADER]: JSON.stringify({
      mode: "user_selected",
      providerId: "openai-image",
      modelId: MODEL,
      credentialSource: "server_environment",
      ...overrides,
    }),
  };
}

function openAIImageStub(response: () => Response = () => new Response(
  JSON.stringify({ created: 1234, data: [{ b64_json: VALID_PNG_B64 }] }),
  { status: 200, headers: { "Content-Type": "application/json" } }
)) {
  const calls: { url: string; auth?: string; body?: string }[] = [];
  const fetchMock = vi.fn(async (input: unknown, init?: RequestInit) => {
    const url = typeof input === "string" ? input : String((input as { url?: string })?.url);
    calls.push({
      url,
      auth: (init?.headers as Record<string, string> | undefined)?.Authorization,
      body: typeof init?.body === "string" ? init.body : undefined,
    });
    return response();
  }) as unknown as typeof fetch;
  return { fetchMock, calls };
}

async function boot(env: Record<string, string>, fetchImpl?: typeof fetch, store?: ImagePreviewStore) {
  vi.resetModules();
  for (const k of ENV_KEYS) delete process.env[k];
  Object.assign(process.env, env);
  if (fetchImpl) globalThis.fetch = fetchImpl;
  const { createApp } = await import("../../server/app.js");
  const app = createApp({ isProduction: false, ...(store ? { imagePreviewStore: store } : {}) });
  const server = http.createServer(app);
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  const addr = server.address() as AddressInfo;
  const baseUrl = `http://127.0.0.1:${addr.port}`;
  const session = await bootstrapImageSession(baseUrl, realFetch);
  return {
    baseUrl,
    cookie: session.cookie,
    close: () => new Promise<void>((r) => server.close(() => r())),
  };
}

async function quote(
  baseUrl: string,
  headers: Record<string, string>,
  body: Record<string, unknown> = {},
  cookie?: string
) {
  const res = await realFetch(`${baseUrl}/api/recipes/image/quote`, {
    method: "POST",
    headers: { ...headers, ...(cookie ? { Cookie: cookie } : {}) },
    body: JSON.stringify(body),
  });
  return { status: res.status, body: (await res.json()) as Record<string, unknown> };
}

async function generate(
  baseUrl: string,
  headers: Record<string, string>,
  body: Record<string, unknown>,
  cookie?: string
) {
  const res = await realFetch(`${baseUrl}/api/recipes/image/generate`, {
    method: "POST",
    headers: { ...headers, ...(cookie ? { Cookie: cookie } : {}) },
    body: JSON.stringify(body),
  });
  return { status: res.status, body: (await res.json()) as Record<string, unknown> };
}

beforeEach(() => {
  vi.restoreAllMocks();
});

afterEach(() => {
  globalThis.fetch = realFetch;
  for (const k of ENV_KEYS) delete process.env[k];
  vi.resetModules();
});

describe("P2 — OpenAI Image quote + generate through the secure workflow", () => {
  it("OpenAI Image is OPT-IN: with no selection header the server default remains Gemini and OpenAI is never called", async () => {
    const stub = openAIImageStub();
    // OPENAI_API_KEY exists, but GEMINI_API_KEY does not -> default is unavailable.
    const app = await boot({ OPENAI_API_KEY: KEY }, stub.fetchMock);
    try {
      const q = await quote(app.baseUrl, { "Content-Type": "application/json" }, { title: "Soup" }, app.cookie);
      expect(q.status).toBe(503);
      expect(q.body["code"]).toBe("IMAGE_PROVIDER_NOT_CONFIGURED");
      expect(stub.calls).toHaveLength(0);
    } finally {
      await app.close();
    }
  });

  it("quote makes ZERO provider calls and issues a single-use token for OpenAI Image", async () => {
    const stub = openAIImageStub();
    const app = await boot({ OPENAI_API_KEY: KEY }, stub.fetchMock);
    try {
      const q = await quote(app.baseUrl, selectionHeader(), { title: "Soup" }, app.cookie);
      expect(q.status).toBe(200);
      expect(q.body["provider"]).toEqual({ id: "openai-image", name: "OpenAI Image" });
      expect(q.body["model"]).toBe(MODEL);
      expect(q.body["costClass"]).toBe("variable");
      expect(q.body["requiresConfirmation"]).toBe(true);
      expect(typeof q.body["confirmationToken"]).toBe("string");
      expect(stub.calls).toHaveLength(0);
    } finally {
      await app.close();
    }
  });

  it("generate without a token is rejected with ZERO provider calls", async () => {
    const stub = openAIImageStub();
    const app = await boot({ OPENAI_API_KEY: KEY }, stub.fetchMock);
    try {
      const res = await generate(app.baseUrl, selectionHeader(), { title: "Soup" }, app.cookie);
      expect(res.status).toBe(409);
      expect(res.body["code"]).toBe("IMAGE_CONFIRMATION_REQUIRED");
      expect(stub.calls).toHaveLength(0);
    } finally {
      await app.close();
    }
  });

  it("a valid token authorizes EXACTLY ONE OpenAI call and returns a transient preview token (no vault write)", async () => {
    const stub = openAIImageStub();
    const store = new ImagePreviewStore({ scheduleCleanup: () => () => {} });
    const app = await boot({ OPENAI_API_KEY: KEY }, stub.fetchMock, store);
    try {
      const q = await quote(app.baseUrl, selectionHeader(), { title: "Soup" }, app.cookie);
      const token = q.body["confirmationToken"] as string;
      const res = await generate(app.baseUrl, selectionHeader(), { title: "Soup", confirmationToken: token }, app.cookie);
      expect(res.status).toBe(200);
      expect(res.body["provider"]).toBe("openai-image");
      expect(res.body["model"]).toBe(MODEL);
      expect(res.body["contentType"]).toBe("image/png");
      expect(typeof res.body["token"]).toBe("string");
      // The response carries ONLY preview token metadata, never image base64.
      expect(JSON.stringify(res.body)).not.toContain(VALID_PNG_B64);

      // Exactly one provider call, to the fixed OpenAI endpoint, with the key in
      // the Authorization header ONLY (never in the body).
      expect(stub.calls).toHaveLength(1);
      expect(stub.calls[0].url).toBe("https://api.openai.com/v1/images/generations");
      expect(stub.calls[0].auth).toBe(`Bearer ${KEY}`);
      expect(stub.calls[0].body).not.toContain(KEY);

      // The single-use token can NEVER authorize a second call.
      const second = await generate(app.baseUrl, selectionHeader(), { title: "Soup", confirmationToken: token }, app.cookie);
      expect(second.status).toBe(409);
      expect(second.body["code"]).toBe("IMAGE_CONFIRMATION_INVALID");
      expect(stub.calls).toHaveLength(1);

      // Preview bytes are retrievable by opaque token with a safe content type.
      const preview = await realFetch(`${app.baseUrl}/api/recipes/image/preview/${res.body["token"]}`, {
        headers: { Cookie: app.cookie },
      });
      expect(preview.status).toBe(200);
      expect(preview.headers.get("content-type")).toBe("image/png");
      expect(preview.headers.get("cache-control")).toBe("no-store");
    } finally {
      await app.close();
    }
  });

  it("an organization-verification failure maps to a distinct bounded 403", async () => {
    const stub = openAIImageStub(
      () =>
        new Response(
          JSON.stringify({
            error: {
              message: "Your organization must be verified to use the model `gpt-image-2.6-flare`.",
              code: "organization_verification_required",
            },
          }),
          { status: 403, headers: { "Content-Type": "application/json" } }
        )
    );
    const app = await boot({ OPENAI_API_KEY: KEY }, stub.fetchMock);
    try {
      const q = await quote(app.baseUrl, selectionHeader(), { title: "Soup" }, app.cookie);
      const token = q.body["confirmationToken"] as string;
      const res = await generate(app.baseUrl, selectionHeader(), { title: "Soup", confirmationToken: token }, app.cookie);
      expect(res.status).toBe(403);
      expect(res.body["code"]).toBe("IMAGE_PROVIDER_ORGANIZATION_UNVERIFIED");
      expect(String(res.body["error"])).toMatch(/organization must be verified/i);
      expect(stub.calls).toHaveLength(1);
    } finally {
      await app.close();
    }
  });
});
