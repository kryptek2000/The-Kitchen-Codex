/**
 * SHISO-C1.6-F3 — Signature Recipe Card.
 *
 * Read-only, cookbook-style presentation of a validated GeneratedRecipeDraft.
 * This component is deliberately presentational: it never saves, never edits,
 * and never invents fields. The structured editor lives behind the modal's
 * explicit "Edit Recipe" action. Photography is rendered only when the caller
 * supplies a genuinely associated image; a generated draft with no image keeps
 * the image-free editorial composition.
 */
import React from 'react';
import type {
  GeneratedRecipeDraft,
  GeneratedRecipeProvenance,
} from '../schema/generatedRecipe';

export interface RecipeCardImage {
  /** A URL the caller has already established as legitimately associated. */
  url: string;
  alt: string;
  /** Optional truthful attribution shown in the figure caption. */
  credit?: string;
}

interface SignatureRecipeCardProps {
  draft: GeneratedRecipeDraft;
  provenance: GeneratedRecipeProvenance;
  image?: RecipeCardImage | null;
}

/** Vulgar fractions used for display only; the draft keeps its numeric value. */
const DISPLAY_FRACTIONS: ReadonlyArray<readonly [number, string]> = [
  [1 / 8, '⅛'],
  [1 / 4, '¼'],
  [1 / 3, '⅓'],
  [3 / 8, '⅜'],
  [1 / 2, '½'],
  [5 / 8, '⅝'],
  [2 / 3, '⅔'],
  [3 / 4, '¾'],
  [7 / 8, '⅞'],
];

/**
 * Friendly cookbook quantities: 1.25 -> "1¼", 0.75 -> "¾", 0.25 -> "¼".
 * This is presentation only — the underlying numeric amount is never changed,
 * so the structured editor and the save path keep the original value.
 */
function formatAmount(amount: number | null | undefined): string {
  if (amount === null || amount === undefined || !Number.isFinite(amount) || amount <= 0) return '';
  const whole = Math.floor(amount + 1e-9);
  const remainder = amount - whole;
  if (remainder < 1e-9) return String(whole);
  let glyph: string | null = null;
  let distance = Number.POSITIVE_INFINITY;
  for (const [value, candidate] of DISPLAY_FRACTIONS) {
    const delta = Math.abs(remainder - value);
    if (delta < distance) {
      distance = delta;
      glyph = candidate;
    }
  }
  if (glyph && distance <= 0.02) return `${whole ? `${whole}` : ''}${glyph}`;
  return String(Number(amount.toFixed(2)));
}

/** Delicate botanical rule from the approved Signature Recipe Card mockup. */
